// Generates src/styles/fonts.generated.css from the @fontsource packages.
// Keeps only the woff2 sources (every target browser supports woff2), so the
// single-file build does not inline every font twice.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const sources = [
  ['@fontsource/dotgothic16', '400.css'],
  ['@fontsource/jetbrains-mono', 'latin-400.css'],
  ['@fontsource/jetbrains-mono', 'latin-700.css'],
];

let out = '/* Generated by scripts/gen-fonts.mjs. Do not edit. Fonts: SIL OFL 1.1, see LICENSES.md */\n';
for (const [pkg, file] of sources) {
  const dir = path.dirname(require.resolve(`${pkg}/package.json`));
  const css = readFileSync(path.join(dir, file), 'utf8')
    .replace(/,\s*url\([^)]+\.woff\)\s*format\('woff'\)/g, '')
    .replace(/url\(\.\/files\//g, `url(${pkg}/files/`)
    .replace(/font-display:\s*swap/g, 'font-display: block');
  out += css + '\n';
}
writeFileSync(new URL('../src/styles/fonts.generated.css', import.meta.url), out);
console.log('wrote src/styles/fonts.generated.css');
