// Generates the ending slide's QR code at build time (no network at run time).
// Writes src/content/qr.generated.js: one SVG path of dark modules + the module count.
// The URL is Saman's LinkedIn profile (given in the Phase 3b brief).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const qrcode = createRequire(import.meta.url)('qrcode-generator');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const QR_URL = 'https://www.linkedin.com/in/samabaasi';

const qr = qrcode(0, 'M'); // automatic version, error correction M
qr.addData(QR_URL);
qr.make();
const n = qr.getModuleCount();
let d = '';
for (let r = 0; r < n; r++) for (let c = 0; c < n; c++) if (qr.isDark(r, c)) d += `M${c} ${r}h1v1h-1z`;
const out = `// Generated by scripts/gen-qr.mjs at build time. Do not edit.
export const QR_URL = ${JSON.stringify(QR_URL)};
export const QR_MODULES = ${n};
export const QR_PATH = ${JSON.stringify(d)};
`;
writeFileSync(path.join(root, 'src/content/qr.generated.js'), out);
console.log(`QR: ${n}×${n} modules for ${QR_URL}`);
