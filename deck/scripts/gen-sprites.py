# Converts the boss-room pixel art (assets-src/boss-sprites/*.png, drawn in code by the Python
# scripts next to them) into src/sprites/pack.generated.js: one entry per sprite with its size,
# a palette (char -> colour) and rows of chars ('.' = transparent). The deck stays a single
# offline HTML file and draws these with integer scaling only.
# Run: python3 -I scripts/gen-sprites.py   (no network; PIL only)
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets-src', 'boss-sprites')
# Only the dragon is used in the deck (Saman chose to keep the deck's own goblins, castle and sword).
NAMES = ['dragon_idle', 'dragon_anticipation', 'dragon_breath', 'dragon_hurt', 'dragon_kneel', 'dragon_defeated']
CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789@#$%&*+-=?!<>:;'

out = {}
for n in NAMES:
    im = Image.open(os.path.join(SRC, n + '.png')).convert('RGBA')
    w, h = im.size
    pal, rows = {}, []
    for y in range(h):
        row = ''
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a == 0:
                row += '.'
                continue
            col = '#%02x%02x%02x' % (r, g, b)
            if col not in pal:
                pal[col] = CHARS[len(pal)]
            row += pal[col]
        rows.append(row)
    out[n] = {'w': w, 'h': h, 'pal': {c: col for col, c in pal.items()}, 'rows': rows}

meta = {
    'dragon': json.load(open(os.path.join(SRC, 'dragon.json'))),
    'swaps': json.load(open(os.path.join(SRC, 'palette_swaps.json'))),
}
js = '// Generated by scripts/gen-sprites.py from assets-src/boss-sprites. Do not edit.\n'
js += 'export const PACK = ' + json.dumps(out, separators=(',', ':')) + ';\n'
js += 'export const PACK_META = ' + json.dumps(meta, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'src', 'sprites', 'pack.generated.js'), 'w').write(js)
print('sprites:', len(out), 'bytes:', len(js))
